defmodule Podium.Chart do
  @moduledoc """
  Chart struct and XML generation for embedding charts in slides.

  A chart combines a chart type, chart data, and formatting options (title,
  legend, axes, data labels). The chart XML is generated by `Podium.Chart.XmlWriter`
  and the embedded Excel workbook by `Podium.Chart.XlsxWriter`.
  """

  alias Podium.OPC.Constants
  alias Podium.Units

  defstruct [
    :chart_type,
    :chart_data,
    :chart_index,
    :x,
    :y,
    :width,
    :height,
    :title,
    :legend,
    :combo,
    :background,
    :gap_width,
    :overlap,
    :vary_by_categories,
    :bubble_scale,
    data_labels: [],
    category_axis: [],
    value_axis: [],
    secondary_value_axis: [],
    text: [],
    plot_area: []
  ]

  @type t :: %__MODULE__{
          chart_type: Podium.chart_type() | :combo,
          chart_data: struct(),
          chart_index: pos_integer() | nil,
          x: non_neg_integer(),
          y: non_neg_integer(),
          width: non_neg_integer(),
          height: non_neg_integer(),
          title: String.t() | keyword() | nil,
          legend: atom() | keyword() | false | nil,
          combo: Podium.Chart.ComboChart.t() | nil,
          background: Podium.fill() | keyword() | nil,
          gap_width: 0..500 | nil,
          overlap: -100..100 | nil,
          vary_by_categories: boolean() | nil,
          bubble_scale: 0..300 | nil,
          data_labels: keyword() | [atom()],
          category_axis: keyword(),
          value_axis: keyword(),
          secondary_value_axis: keyword(),
          text: keyword(),
          plot_area: keyword()
        }

  @doc """
  Creates a new chart.
  """
  @spec new(atom(), struct(), keyword()) :: t()
  def new(chart_type, chart_data, opts) do
    %__MODULE__{
      chart_type: chart_type,
      chart_data: chart_data,
      chart_index: nil,
      x: Units.to_emu(Keyword.fetch!(opts, :x)),
      y: Units.to_emu(Keyword.fetch!(opts, :y)),
      width: Units.to_emu(Keyword.fetch!(opts, :width)),
      height: Units.to_emu(Keyword.fetch!(opts, :height)),
      title: validate_title!(Keyword.get(opts, :title)),
      legend: validate_legend!(Keyword.get(opts, :legend)),
      data_labels: Keyword.get(opts, :data_labels, []),
      category_axis: validate_axis!(Keyword.get(opts, :category_axis, []), :category_axis),
      value_axis: validate_axis!(Keyword.get(opts, :value_axis, []), :value_axis),
      text: Keyword.get(opts, :text, []),
      background: validate_background!(Keyword.get(opts, :background)),
      plot_area: validate_plot_area!(Keyword.get(opts, :plot_area, []))
    }
    |> put_plot_options(opts, [chart_type])
    |> validate_chart_labels!()
  end

  @doc """
  Creates a new combo chart.
  """
  @spec new_combo(Podium.Chart.ComboChart.t(), keyword()) :: t()
  def new_combo(%Podium.Chart.ComboChart{} = combo, opts) do
    %__MODULE__{
      chart_type: :combo,
      chart_data: combo.chart_data,
      chart_index: nil,
      combo: combo,
      x: Units.to_emu(Keyword.fetch!(opts, :x)),
      y: Units.to_emu(Keyword.fetch!(opts, :y)),
      width: Units.to_emu(Keyword.fetch!(opts, :width)),
      height: Units.to_emu(Keyword.fetch!(opts, :height)),
      title: validate_title!(Keyword.get(opts, :title)),
      legend: validate_legend!(Keyword.get(opts, :legend)),
      data_labels: Keyword.get(opts, :data_labels, []),
      category_axis: validate_axis!(Keyword.get(opts, :category_axis, []), :category_axis),
      value_axis: validate_axis!(Keyword.get(opts, :value_axis, []), :value_axis),
      secondary_value_axis:
        validate_axis!(Keyword.get(opts, :secondary_value_axis, []), :secondary_value_axis),
      text: Keyword.get(opts, :text, []),
      background: validate_background!(Keyword.get(opts, :background)),
      plot_area: validate_plot_area!(Keyword.get(opts, :plot_area, []))
    }
    |> put_plot_options(opts, Enum.map(combo.plots, & &1.chart_type))
    |> validate_chart_labels!()
  end

  defp validate_chart_labels!(%__MODULE__{combo: nil} = chart) do
    validate_data_labels!(chart.data_labels, chart.chart_type, "chart :data_labels")
    validate_series_labels!(chart.chart_data.series, chart.chart_type)
    chart
  end

  defp validate_chart_labels!(%__MODULE__{combo: combo} = chart) do
    Enum.each(combo.plots, fn plot ->
      labels = if is_nil(plot.data_labels), do: chart.data_labels, else: plot.data_labels
      where = "#{inspect(plot.chart_type)} plot :data_labels"
      validate_data_labels!(labels, plot.chart_type, where)

      plot.series_indices
      |> Enum.map(&Enum.at(combo.chart_data.series, &1))
      |> validate_series_labels!(plot.chart_type)
    end)

    chart
  end

  defp validate_series_labels!(series_list, chart_type) do
    Enum.each(series_list, fn series ->
      validate_data_labels!(
        series.data_labels,
        chart_type,
        "series #{inspect(series.name)} :data_labels"
      )
    end)
  end

  @label_contents [:value, :category, :series, :percent, :legend_key, :bubble_size]

  @doc false
  # Validates data labels (chart-level, plot, series or per-point) for a chart
  # type: what they show, and a position the chart type accepts.
  @spec validate_data_labels!(term(), atom(), String.t()) :: :ok
  def validate_data_labels!(labels, _chart_type, _where) when labels in [nil, [], %{}], do: :ok

  def validate_data_labels!(points, chart_type, where) when is_map(points) do
    Enum.each(points, fn {idx, opts} ->
      validate_data_labels!(opts, chart_type, "#{where} point #{inspect(idx)}")
    end)
  end

  def validate_data_labels!(labels, chart_type, where) when is_list(labels) do
    {show, opts} =
      if Keyword.keyword?(labels),
        do: {Keyword.get(labels, :show, [:value]), labels},
        else: {labels, []}

    case show -- @label_contents do
      [] ->
        :ok

      unknown ->
        raise ArgumentError,
              "#{where} cannot show #{inspect(unknown)}; " <>
                "choose from #{inspect(@label_contents)}"
    end

    case Keyword.get(opts, :position) do
      nil ->
        :ok

      position ->
        allowed = Podium.Chart.ChartType.label_positions(chart_type)

        unless position in allowed do
          raise ArgumentError,
                "#{where} position #{inspect(position)} is not available on " <>
                  "#{inspect(chart_type)} charts; " <>
                  if(allowed == [],
                    do: "they take no label position",
                    else: "choose from #{inspect(allowed)}"
                  )
        end
    end

    case Keyword.get(opts, :separator) do
      separator when is_nil(separator) or is_binary(separator) ->
        :ok

      other ->
        raise ArgumentError, "#{where} :separator must be a string, got: #{inspect(other)}"
    end

    validate_data_labels!(Keyword.get(opts, :points), chart_type, where)
  end

  def validate_data_labels!(other, _chart_type, where) do
    raise ArgumentError,
          "#{where} must be a list or a map of point index to options, got: #{inspect(other)}"
  end

  @plot_option_keys [:gap_width, :overlap, :vary_by_categories, :bubble_scale]

  # Chart-level plot options apply to every plot of the chart (in a combo, to
  # every plot that does not set its own).
  defp put_plot_options(chart, opts, chart_types) do
    plot_opts = Keyword.take(opts, @plot_option_keys)
    validate_plot_options!(plot_opts, chart_types, "chart")
    struct(chart, plot_opts)
  end

  @doc false
  # Validates plot options (:gap_width, :overlap, :vary_by_categories,
  # :bubble_scale) given for plots of `chart_types`. `where` names the
  # option's owner in error messages.
  @spec validate_plot_options!(keyword(), [atom()], String.t()) :: :ok
  def validate_plot_options!(opts, chart_types, where) do
    elements = Enum.map(chart_types, &Podium.Chart.ChartType.config(&1).element)

    Enum.each(opts, fn
      {_key, nil} ->
        :ok

      {:gap_width, value} ->
        validate_int!(value, 0..500, where, :gap_width)
        require_element!(elements, "c:barChart", where, :gap_width, "bar and column")

      {:overlap, value} ->
        validate_int!(value, -100..100, where, :overlap)
        require_element!(elements, "c:barChart", where, :overlap, "bar and column")

      {:bubble_scale, value} ->
        validate_int!(value, 0..300, where, :bubble_scale)
        require_element!(elements, "c:bubbleChart", where, :bubble_scale, "bubble")

      {:vary_by_categories, value} when is_boolean(value) ->
        :ok

      {:vary_by_categories, value} ->
        raise ArgumentError,
              "#{where} :vary_by_categories must be a boolean, got: #{inspect(value)}"

      _other ->
        :ok
    end)
  end

  defp validate_int!(value, range, where, key) do
    unless is_integer(value) and value in range do
      raise ArgumentError,
            "#{where} #{inspect(key)} must be an integer between #{range.first} and " <>
              "#{range.last}, got: #{inspect(value)}"
    end
  end

  defp require_element!(elements, element, where, key, kind) do
    unless element in elements do
      raise ArgumentError, "#{where} #{inspect(key)} applies to #{kind} charts only"
    end
  end

  defp validate_background!(background)
       when is_nil(background) or background == :none or is_binary(background) or
              is_list(background) or is_tuple(background),
       do: background

  defp validate_background!(other) do
    raise ArgumentError,
          "chart :background must be :none, a fill or a keyword list with :fill and :line, " <>
            "got: #{inspect(other)}"
  end

  defp validate_plot_area!(opts) when is_list(opts) do
    validate_layout!(opts, ":plot_area", :required)

    case Keyword.get(opts, :target, :inner) do
      target when target in [:inner, :outer] ->
        opts

      other ->
        raise ArgumentError,
              "chart :plot_area :target must be :inner or :outer, got: #{inspect(other)}"
    end
  end

  defp validate_plot_area!(other) do
    raise ArgumentError, "chart :plot_area must be a keyword list, got: #{inspect(other)}"
  end

  defp validate_title!(title) do
    if keyword_opts?(title), do: validate_layout!(title, ":title", :none)
    title
  end

  defp validate_legend!(legend) do
    if keyword_opts?(legend), do: validate_layout!(legend, ":legend", :optional)
    legend
  end

  defp validate_axis!(axis_opts, name) do
    title = Keyword.get(axis_opts, :title)
    if keyword_opts?(title), do: validate_layout!(title, "#{inspect(name)} :title", :none)

    validate_choice!(axis_opts, name, :tick_label_position, [:next_to, :low, :high, :none])
    validate_choice!(axis_opts, name, :major_tick_mark, [:out, :in, :cross, :none])
    validate_choice!(axis_opts, name, :minor_tick_mark, [:out, :in, :cross, :none])
    validate_choice!(axis_opts, name, :type, [:date])
    validate_choice!(axis_opts, name, :base_time_unit, [:days, :months, :years])
    validate_choice!(axis_opts, name, :major_time_unit, [:days, :months, :years])
    validate_choice!(axis_opts, name, :minor_time_unit, [:days, :months, :years])

    case Keyword.get(axis_opts, :crosses) do
      crosses when crosses in [nil, :auto_zero, :min, :max] or is_number(crosses) ->
        :ok

      other ->
        raise ArgumentError,
              "chart #{inspect(name)} :crosses must be :auto_zero, :min, :max or a number, " <>
                "got: #{inspect(other)}"
    end

    case Keyword.get(axis_opts, :label_offset) do
      offset when is_nil(offset) or (is_integer(offset) and offset in 0..1000) ->
        :ok

      other ->
        raise ArgumentError,
              "chart #{inspect(name)} :label_offset must be an integer between 0 and 1000, " <>
                "got: #{inspect(other)}"
    end

    axis_opts
  end

  defp validate_choice!(opts, name, key, choices) do
    case Keyword.get(opts, key) do
      nil ->
        :ok

      value ->
        unless value in choices do
          raise ArgumentError,
                "chart #{inspect(name)} #{inspect(key)} must be one of #{inspect(choices)}, " <>
                  "got: #{inspect(value)}"
        end
    end
  end

  defp keyword_opts?(value), do: is_list(value) and value != [] and Keyword.keyword?(value)

  # Manual layout fractions of the chart frame. :x and :y go together; :w and
  # :h go together, and `size` says whether they are :required, :optional or
  # not taken (:none).
  defp validate_layout!(opts, name, size) do
    position = Enum.map([:x, :y], &Keyword.get(opts, &1))
    dimensions = Enum.map([:w, :h], &Keyword.get(opts, &1))
    given = Enum.reject(position ++ dimensions, &is_nil/1)

    cond do
      given == [] ->
        :ok

      Enum.any?(position, &is_nil/1) ->
        raise ArgumentError, "chart #{name} needs :x and :y together, got: #{inspect(opts)}"

      size == :none and dimensions != [nil, nil] ->
        raise ArgumentError, "chart #{name} takes :x and :y only, got: #{inspect(opts)}"

      size == :required and Enum.any?(dimensions, &is_nil/1) ->
        raise ArgumentError,
              "chart #{name} needs all of :x, :y, :w and :h together, got: #{inspect(opts)}"

      size == :optional and Enum.count(dimensions, &is_nil/1) == 1 ->
        raise ArgumentError, "chart #{name} needs :w and :h together, got: #{inspect(opts)}"

      not Enum.all?(given, &(is_number(&1) and &1 >= 0 and &1 <= 1)) ->
        raise ArgumentError,
              "chart #{name} :x, :y, :w and :h must be fractions between 0 and 1, " <>
                "got: #{inspect(opts)}"

      true ->
        :ok
    end
  end

  @doc """
  Returns the partname for the chart XML.
  """
  @spec partname(t()) :: String.t()
  def partname(%__MODULE__{chart_index: idx}), do: "ppt/charts/chart#{idx}.xml"

  @doc """
  Returns the rels partname for this chart.
  """
  @spec rels_partname(t()) :: String.t()
  def rels_partname(%__MODULE__{chart_index: idx}),
    do: "ppt/charts/_rels/chart#{idx}.xml.rels"

  @doc """
  Returns the partname for the embedded Excel workbook.
  """
  @spec xlsx_partname(t()) :: String.t()
  def xlsx_partname(%__MODULE__{chart_index: idx}),
    do: "ppt/embeddings/Microsoft_Excel_Sheet#{idx}.xlsx"

  @doc """
  Generates the graphic frame XML for embedding the chart in a slide.
  The `shape_id` is the shape ID within the slide, and `r_id` is the
  relationship ID linking to the chart part.
  """
  @spec graphic_frame_xml(t(), pos_integer(), String.t()) :: String.t()
  def graphic_frame_xml(%__MODULE__{} = chart, shape_id, r_id) do
    ns_a = Constants.ns(:a)
    ns_p = Constants.ns(:p)
    ns_r = Constants.ns(:r)
    ns_c = Constants.ns(:c)

    ~s(<p:graphicFrame xmlns:a="#{ns_a}" xmlns:p="#{ns_p}" xmlns:r="#{ns_r}">) <>
      ~s(<p:nvGraphicFramePr>) <>
      ~s(<p:cNvPr id="#{shape_id}" name="Chart #{chart.chart_index}"/>) <>
      ~s(<p:cNvGraphicFramePr><a:graphicFrameLocks noGrp="1"/></p:cNvGraphicFramePr>) <>
      ~s(<p:nvPr/>) <>
      ~s(</p:nvGraphicFramePr>) <>
      ~s(<p:xfrm>) <>
      ~s(<a:off x="#{chart.x}" y="#{chart.y}"/>) <>
      ~s(<a:ext cx="#{chart.width}" cy="#{chart.height}"/>) <>
      ~s(</p:xfrm>) <>
      ~s(<a:graphic>) <>
      ~s(<a:graphicData uri="#{ns_c}">) <>
      ~s(<c:chart xmlns:c="#{ns_c}" r:id="#{r_id}"/>) <>
      ~s(</a:graphicData>) <>
      ~s(</a:graphic>) <>
      ~s(</p:graphicFrame>)
  end
end
